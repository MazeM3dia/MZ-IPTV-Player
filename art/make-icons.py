"""Builds every icon from art/icon.jpg:

    python art/make-icons.py

  android/app/src/main/res/   launcher icons (adaptive, themed, legacy) + TV banner
  web/icons/                  browser tab icon + home-screen icons
  art/store/                  Play Store graphics (not packaged in the app)

Needs Pillow + numpy, and Chrome for the banner / feature graphic (it renders
art/banner.html and art/feature.html with the app's bundled Inter font).

The source artwork's logo runs almost to its edges, but launchers only show
the centre 72 of 108 dp (and crop that to a circle, squircle, ...). So the
artwork is scaled to SCALE and the gradient behind it is extended outwards
(fitted from the artwork's border) to fill the full 108 dp layer.
"""
import os
import subprocess
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art", "icon.jpg")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
WEB_ICONS = os.path.join(ROOT, "web", "icons")
STORE = os.path.join(ROOT, "art", "store")
SCALE = 0.62          # logo stays inside the 66 dp safe circle
N = 1080              # working canvas = 108 dp
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"


def feats(x, y):
    return np.stack([np.ones_like(x), x, y, x * y, x * x, y * y], -1)


def build_master():
    """108 dp canvas: extended gradient + scaled artwork. Also returns the bare gradient."""
    src = Image.open(SRC).convert("RGB").resize((N, N), Image.LANCZOS)
    im = np.asarray(src).astype(float)
    yy, xx = np.mgrid[0:N, 0:N] / (N - 1)
    ring = np.zeros((N, N), bool)
    b = N // 12
    ring[:b] = ring[-b:] = True
    ring[:, :b] = ring[:, -b:] = True
    coef = [np.linalg.lstsq(feats(xx[ring], yy[ring]), im[..., c][ring], rcond=None)[0] for c in range(3)]
    off = (1 - SCALE) / 2
    X, Y = (xx - off) / SCALE, (yy - off) / SCALE      # canvas -> artwork coords
    bg = np.clip(np.stack([feats(X, Y) @ coef[c] for c in range(3)], -1), 0, 255).astype(np.uint8)
    canvas = Image.fromarray(bg)
    size = round(N * SCALE)
    art = src.resize((size, size), Image.LANCZOS)
    mask = Image.new("L", (size, size), 0)
    f = round(size * 0.06)
    mask.paste(255, (f, f, size - f, size - f))
    mask = mask.filter(ImageFilter.GaussianBlur(f / 2))   # melt the art's edge into the gradient
    p = round(N * off)
    canvas.paste(art, (p, p), mask)
    return canvas, Image.fromarray(bg)


def build_monochrome(master, bg):
    """Themed icon (Android 13+): the parts brighter than the gradient, as a white silhouette."""
    m = np.asarray(master.filter(ImageFilter.GaussianBlur(1.5))).astype(float)
    d = np.clip((m - np.asarray(bg).astype(float)).max(2), 0, None)
    alpha = Image.fromarray((np.clip((d - 95) / 40, 0, 1) * 255).astype(np.uint8)).filter(ImageFilter.MedianFilter(5))
    out = Image.new("RGBA", (N, N), (255, 255, 255, 0))
    out.putalpha(alpha)
    return out


def legacy(master, px, round_):
    """Pre-Android-8 icon (48 dp): the visible 72 dp, shaped, with a 1 dp margin."""
    vis = master.crop((N // 6, N // 6, N - N // 6, N - N // 6))
    big = px * 4
    pad = round(big / 48)
    inner = big - 2 * pad
    m = Image.new("L", (inner, inner), 0)
    d = ImageDraw.Draw(m)
    if round_:
        d.ellipse((0, 0, inner - 1, inner - 1), 255)
    else:
        d.rounded_rectangle((0, 0, inner - 1, inner - 1), inner * 0.18, 255)
    out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    out.paste(vis.resize((inner, inner), Image.LANCZOS), (pad, pad), m)
    return out.resize((px, px), Image.LANCZOS)


def write(img, folder, name):
    d = os.path.join(RES, folder)
    os.makedirs(d, exist_ok=True)
    img.save(os.path.join(d, name), optimize=True)


def adaptive_xml():
    xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by art/make-icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""
    d = os.path.join(RES, "mipmap-anydpi-v26")
    os.makedirs(d, exist_ok=True)
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(xml)


def colors_xml(bg):
    r, g, b = np.asarray(bg).reshape(-1, 3).mean(0).round().astype(int)
    with open(os.path.join(RES, "values", "colors.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
                "    <!-- Adaptive icon backdrop; the foreground layer is opaque, so this only shows while it loads. -->\n"
                f'    <color name="ic_launcher_background">#{r:02X}{g:02X}{b:02X}</color>\n</resources>\n')


def visible(master, px):
    """The centre 72 dp - what a launcher shows - as a plain square."""
    return master.crop((N // 6, N // 6, N - N // 6, N - N // 6)).resize((px, px), Image.LANCZOS)


def render(page, w, h, scale):
    """Screenshot an art/*.html page with Chrome; returns a w*scale x h*scale image."""
    art = os.path.join(ROOT, "art")
    shot = os.path.join(art, "build-shot.png")
    url = "file:///" + os.path.join(art, page).replace("\\", "/")
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--allow-file-access-from-files",
                    f"--force-device-scale-factor={scale}", f"--window-size={w},{h}", "--screenshot=" + shot, url],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    img = Image.open(shot).convert("RGB")
    img.load()
    os.remove(shot)
    return img


def banners(master):
    """TV home-screen banner (160x90 dp) + Play Store TV banner and feature graphic."""
    if not os.path.exists(CHROME):
        print("Chrome not found - banners skipped")
        return
    tile = os.path.join(ROOT, "art", "build-banner-icon.png")   # the icon tile both pages show
    visible(master, 576).save(tile)
    try:
        big = render("banner.html", 320, 180, 4)                # 1280x720
        write(big.resize((320, 180), Image.LANCZOS), "drawable-xhdpi", "banner.png")
        write(big.resize((640, 360), Image.LANCZOS), "drawable-xxxhdpi", "banner.png")
        save(big, STORE, "tv-banner-1280x720.png")
        feature = render("feature.html", 1024, 500, 2)          # 2048x1000
        save(feature.resize((1024, 500), Image.LANCZOS), STORE, "feature-graphic-1024x500.png")
    finally:
        os.remove(tile)


def save(img, folder, name):
    os.makedirs(folder, exist_ok=True)
    img.save(os.path.join(folder, name), optimize=True)


def web_icons(master):
    """Browser tab + home-screen icons for web/index.html (also packaged in the app, ~40 KB)."""
    save(legacy(master, 32, False), WEB_ICONS, "favicon-32.png")
    save(legacy(master, 192, False), WEB_ICONS, "icon-192.png")
    save(visible(master, 180), WEB_ICONS, "apple-touch-icon.png")   # opaque square; iOS rounds it


def store_icon(master):
    """Play Store icon: 512x512 32-bit PNG, full square (Play rounds the corners)."""
    save(visible(master, 512).convert("RGBA"), STORE, "play-icon-512.png")


def main():
    master, bg = build_master()
    mono = build_monochrome(master, bg)
    for folder, k in DENSITIES.items():
        layer = round(108 * k)
        write(master.resize((layer, layer), Image.LANCZOS), "mipmap-" + folder, "ic_launcher_foreground.png")
        write(mono.resize((layer, layer), Image.LANCZOS), "mipmap-" + folder, "ic_launcher_monochrome.png")
        write(legacy(master, round(48 * k), False), "mipmap-" + folder, "ic_launcher.png")
        write(legacy(master, round(48 * k), True), "mipmap-" + folder, "ic_launcher_round.png")
    adaptive_xml()
    colors_xml(bg)
    web_icons(master)
    store_icon(master)
    banners(master)
    print("Icons written to", RES, WEB_ICONS, STORE, sep="\n  ")


if __name__ == "__main__":
    sys.exit(main())
